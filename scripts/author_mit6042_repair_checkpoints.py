def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def atomic_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)


def author_unit(root: Path, unit_id: str, worker_id: str) -> None:
    base = root / "outputs" / COURSE / BASELINE / "courses" / COURSE / "units" / unit_id
    target = root / "outputs" / COURSE / BUILD / "courses" / COURSE / "units" / unit_id
    if not base.is_dir():
        raise FileNotFoundError(base)
    for stage in ("01-evidence-plan.json", "02-learning-content.json"):
        value = load_json(base / stage)
        value["repair_build_id"] = BUILD
        value["authoring_worker"] = worker_id
        value["source_reference"] = "read-only baseline used as source-backed drafting reference; content checkpoint regenerated for repair build"
        atomic_json(target / stage, value)

    old = load_json(base / "03-practice-flow.json")
    specs = PRACTICE[unit_id]
    old_items = old.get("practice") or []
    if len(old_items) != len(specs):
        raise ValueError(f"{unit_id}: baseline has {len(old_items)} practices, repair specs have {len(specs)}")
    repaired: list[dict[str, Any]] = []
    for old_item, spec in zip(old_items, specs):
        question, hint, deliverable, changed = spec
        citations = old_item.get("citations") or []
        if not citations:
            raise ValueError(f"{unit_id}/{old_item.get('id')}: missing citations")
        repaired.append(
            {
                "id": old_item["id"],
                "level": old_item.get("level", "应用"),
                "question": question,
                "hint": hint,
                "deliverable": deliverable,
                "expected_evidence": [
                    "给出题目中所有指定对象、输入、状态或数值的逐步计算/推理。",
                    "报告一个可观察的最终结果，并用所列 source_id@page 说明使用的定义、规则或方法。",
                    f"处理改变条件：{changed}",
                ],
                "evaluation": {
                    "criteria": [
                        "题目给定的每个输入、约束和符号都被使用且前后一致。",
                        "中间步骤足以复核，最终结果可由读者独立检查。",
                        "改变条件后的结论明确区分保持、变化或前提失效。",
                        "引用页支持所用定义/规则，而非只支持单元标题。",
                    ],
                    "self_check": "逐项核对输入、操作、目标、边界条件、算术结果和页级引用。",
                },
                "citations": citations,
                "content_grounding": {
                    "source_backed_concept": old_item.get("question", "")[:120],
                    "setting_is_fully_specified": True,
                    "transfer_task": True,
                    "lecture_example_replay": False,
                },
            }
        )
    flow = {
        "stage": "practice_flow",
        "version": "0.2.1",
        "status": "completed",
        "course_id": COURSE,
        "course_version": "spring-2024",
        "unit_id": unit_id,
        "integrity": {
            "assessment_type": "new formative practice",
            "graded_answers_reproduced": False,
            "source_homework_reproduced": False,
            "repair_revision": "semantic-repair-20260812",
        },
        "practice": repaired,
        "authoring_worker": worker_id,
        "independent_audit_required_before_finalization": True,
    }
    atomic_json(target / "03-practice-flow.json", flow)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repository-root", type=Path, default=Path("."))
    parser.add_argument("--worker-id", required=True)
    parser.add_argument("--unit", action="append", required=True)
    args = parser.parse_args()
    root = args.repository_root.resolve()
    for unit_id in args.unit:
        if unit_id not in PRACTICE:
            raise SystemExit(f"unknown unit: {unit_id}")
        author_unit(root, unit_id, args.worker_id)
    print(json.dumps({"worker_id": args.worker_id, "units": args.unit, "stages": ["01", "02", "03"], "status": "succeeded"}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
